;1. O que é uma biblioteca?
;Uma biblioteca é um conjunto de funcionalidades que pode ser reutilizado por diferentes aplicações.
;
;2. Aplicação versus biblioteca
;Existe uma diferença importante:
;Aplicação	/ Biblioteca
;Resolve um problema diretamente para o usuário / 	Oferece funcionalidades para outros códigos
;Geralmente possui um fluxo de execução principal / 	Geralmente é utilizada por outras aplicações
;Pode ter interface, API e banco de dados / 	Normalmente expõe funções e dados reutilizáveis